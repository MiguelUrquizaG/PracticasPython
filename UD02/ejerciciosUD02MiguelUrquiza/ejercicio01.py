print(f'\t-Para añadir un número en una posición que indiquemos usamos: .insert(posición,lo que se añade)')
print(f'\t-Observa esta lista --> {lista}')
print("\t-A continuación añadiremos el numero 0 en la primera posición usando lista.insert(0,0)")
lista.insert(0,0)
