print(f'\t-Vamos a utilizar listado*3 para que se imprima 3 veces una cadena')
print(f'\t-El resultado es {lista*3}')
print("-----------------------------------------------------------------------------------------------")
print("4.Combinar listas")
print(f'\t-Para combinar listas utilizaremos: .extend(lista)')
